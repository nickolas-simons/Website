"""Generate tiny blurred placeholders for page backgrounds.

Scans every page's front matter for `background:`, shrinks each image to ~24px
and writes them as inline data URIs to _data/bg_placeholders.yml. The layouts
show the placeholder (stretched, so it looks blurred) until the full image loads.

Re-run after adding or changing a page background:
    python _scripts/bg_placeholders.py
Requires Pillow (pip install Pillow).
"""
import base64, io, re
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
SKIP = {"_site", ".git", ".jekyll-cache", "node_modules", "_scripts"}
SIZE = 24  # longest side, in pixels

backgrounds = set()
for page in ROOT.rglob("*"):
    if page.suffix not in {".md", ".html"} or SKIP & set(page.relative_to(ROOT).parts):
        continue
    text = page.read_text(encoding="utf-8", errors="ignore")
    fm = re.match(r"^---\s*\n(.*?)\n---", text, re.S)
    if fm:
        m = re.search(r"^background:\s*[\"']?([^\"'\s#]+)", fm.group(1), re.M)
        if m:
            backgrounds.add(m.group(1))

lines = ["# Generated by _scripts/bg_placeholders.py - do not edit by hand.",
         "# Maps each page `background:` to a tiny inline placeholder image."]
for bg in sorted(backgrounds):
    src = ROOT / bg.lstrip("/")
    if not src.exists():
        print(f"missing: {bg}")
        continue
    im = Image.open(src).convert("RGB")
    im.thumbnail((SIZE, SIZE), Image.LANCZOS)
    buf = io.BytesIO()
    im.save(buf, "WEBP", quality=60)
    uri = "data:image/webp;base64," + base64.b64encode(buf.getvalue()).decode()
    lines.append(f'"{bg}": "{uri}"')
    print(f"{bg}: {im.size[0]}x{im.size[1]}, {len(uri)} chars")

out = ROOT / "_data" / "bg_placeholders.yml"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"wrote {out.relative_to(ROOT)} ({len(lines) - 2} backgrounds)")
